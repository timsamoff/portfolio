// commit-msg hook logic: enforces this repo's commit conventions
// (CLAUDE.md "Commit style") and strips/blocks AI-attribution trailers.
//
// Usage: node commit-msg-checks.js <path-to-commit-msg-file>
// Mutates the file in place (stripping attribution lines) and exits non-zero
// to block the commit if a hard violation remains after stripping.
'use strict';

const fs = require('fs');

const ATTRIBUTION_PATTERNS = [
    /^Co-Authored-By:/i,
    /^Co-authored-by:/i,
    /^Generated with/i,
    /^Generated by Claude/i,
    /^Claude-Session:/i,
    /^🤖.*Generated/i,
];

function isAttributionLine(line) {
    return ATTRIBUTION_PATTERNS.some(re => re.test(line.trim()));
}

function isCommentLine(line) {
    return line.startsWith('#');
}

function run(msgFilePath) {
    const raw = fs.readFileSync(msgFilePath, 'utf8');
    const lines = raw.split('\n');

    const errors = [];
    const warnings = [];
    let strippedAny = false;

    // Separate real content from trailing git comment block (lines starting with #,
    // which git appends below a cutline and ignores anyway, plus preserve them as-is).
    const contentLines = [];
    const commentLines = [];
    let inComments = false;
    for (const line of lines) {
        if (isCommentLine(line)) {
            inComments = true;
        }
        if (inComments) {
            commentLines.push(line);
        } else {
            contentLines.push(line);
        }
    }

    // Strip attribution lines from the real content.
    const filtered = contentLines.filter(line => {
        if (isAttributionLine(line)) {
            strippedAny = true;
            return false;
        }
        return true;
    });

    // Trim trailing blank lines left behind by stripped attribution.
    while (filtered.length > 0 && filtered[filtered.length - 1].trim() === '') {
        filtered.pop();
    }

    // Re-derive subject/body from the stripped content.
    const nonEmpty = filtered.map((l, i) => ({ l, i })).filter(x => x.l.trim() !== '');
    const subjectIdx = nonEmpty.length > 0 ? nonEmpty[0].i : -1;
    const subject = subjectIdx >= 0 ? filtered[subjectIdx] : '';
    const bodyLines = subjectIdx >= 0 ? filtered.slice(subjectIdx + 1).filter(l => l.trim() !== '') : [];

    // Subject line: a short theme, not a list of everything the commit touched.
    // Detail belongs in body bullets, not jammed into the subject — so this cap is
    // intentionally tight (the classic git 50/72 convention), not just "not absurd".
    if (subject.length > 72) {
        errors.push(`Subject line is ${subject.length} chars — keep it to a short theme (~72 chars max). If there's more to say, put it in body bullets instead of lengthening the subject.`);
    }

    // Body: if present, each line should be a short, high-level bullet — not a
    // narrative sentence describing everything that changed. Cap is intentionally
    // tight; a line needing more room is a sign it's describing implementation
    // detail rather than a one-line summary of what changed.
    for (const line of bodyLines) {
        if (line.length > 80) {
            errors.push(`Body line is too long/narrative (${line.length} chars): "${line.slice(0, 60)}...". Body bullets should be simple, high-level one-liners, not a description of everything that changed.`);
        }
    }

    // Structure: per-line length alone doesn't catch a narrative made of
    // several short-enough lines — multiple blank-line-separated paragraphs
    // in the body is exactly that shape (a prose writeup broken into
    // paragraphs), even if every individual line is under the length cap.
    // Every real bullet-style body in this repo's history has at most one
    // such block (or zero, i.e. no body); a wrapped one-sentence body (no
    // bullet markers) is also fine as long as it's a SINGLE block.
    if (bodyLines.length > 0) {
        let blocks = 0;
        let inBlock = false;
        for (const line of filtered.slice(subjectIdx + 1)) {
            if (line.trim() === '') {
                inBlock = false;
            } else if (!inBlock) {
                blocks++;
                inBlock = true;
            }
        }
        if (blocks > 1) {
            errors.push(`Body has ${blocks} separate paragraph blocks — that's a narrative writeup, not a short theme + bullets. Collapse it to either a single short paragraph, or a flat list of "- " bullets with no blank lines between them.`);
        }

        // "A few bullets", not a sprawling list -- 6 is comfortably above
        // the largest legitimate bullet count seen in this repo's history (4).
        // Non-blocking: a long bullet list is more often a sign the COMMIT
        // itself is doing too much (should be split into smaller commits)
        // than a message-formatting problem to fix by editing the message —
        // so this warns instead of forcing a rewrite of the text in place.
        const bulletLines = bodyLines.filter(l => /^[-*]\s/.test(l.trim()));
        if (bulletLines.length > 6) {
            warnings.push(`Body has ${bulletLines.length} bullets — consider whether this commit is doing too much and would be clearer split into smaller commits, rather than just trimming the list.`);
        }
    }

    // Write back the stripped message (comments preserved, since git needs them
    // for its own diff-below-cutline display; stripping never touches those).
    const newContent = [...filtered, ...(commentLines.length ? [''] : []), ...commentLines].join('\n');
    if (strippedAny) {
        fs.writeFileSync(msgFilePath, newContent, 'utf8');
        console.log('[commit-msg] Stripped attribution/co-author trailer line(s) from commit message.');
    }

    if (subjectIdx === -1) {
        errors.push('Commit message has no subject line.');
    }

    return { errors, warnings };
}

if (require.main === module) {
    const msgFilePath = process.argv[2];
    if (!msgFilePath) {
        console.error('[commit-msg] No commit message file path given.');
        process.exit(1);
    }
    const { errors, warnings } = run(msgFilePath);
    if (warnings.length > 0) {
        console.log('\n[commit-msg] Warnings (non-blocking):');
        for (const w of warnings) console.log(`  - ${w}`);
    }
    if (errors.length > 0) {
        console.log('\n[commit-msg] BLOCKED — commit message convention violations:');
        for (const e of errors) console.log(`  - ${e}`);
        process.exit(1);
    }
}

module.exports = { run, isAttributionLine };
