// commit-msg hook logic: enforces this repo's commit conventions
// (CLAUDE.md "Commit style") and strips/blocks AI-attribution trailers.
//
// Usage: node commit-msg-checks.js <path-to-commit-msg-file>
// Mutates the file in place (stripping attribution lines) and exits non-zero
// to block the commit if a hard violation remains after stripping.
'use strict';

const fs = require('fs');

const ATTRIBUTION_PATTERNS = [
    /^Co-Authored-By:/i,
    /^Co-authored-by:/i,
    /^Generated with/i,
    /^Generated by Claude/i,
    /^Claude-Session:/i,
    /^🤖.*Generated/i,
];

function isAttributionLine(line) {
    return ATTRIBUTION_PATTERNS.some(re => re.test(line.trim()));
}

function isCommentLine(line) {
    return line.startsWith('#');
}

function run(msgFilePath) {
    const raw = fs.readFileSync(msgFilePath, 'utf8');
    const lines = raw.split('\n');

    const errors = [];
    let strippedAny = false;

    // Separate real content from trailing git comment block (lines starting with #,
    // which git appends below a cutline and ignores anyway, plus preserve them as-is).
    const contentLines = [];
    const commentLines = [];
    let inComments = false;
    for (const line of lines) {
        if (isCommentLine(line)) {
            inComments = true;
        }
        if (inComments) {
            commentLines.push(line);
        } else {
            contentLines.push(line);
        }
    }

    // Strip attribution lines from the real content.
    const filtered = contentLines.filter(line => {
        if (isAttributionLine(line)) {
            strippedAny = true;
            return false;
        }
        return true;
    });

    // Trim trailing blank lines left behind by stripped attribution.
    while (filtered.length > 0 && filtered[filtered.length - 1].trim() === '') {
        filtered.pop();
    }

    // Re-derive subject/body from the stripped content.
    const nonEmpty = filtered.map((l, i) => ({ l, i })).filter(x => x.l.trim() !== '');
    const subjectIdx = nonEmpty.length > 0 ? nonEmpty[0].i : -1;
    const subject = subjectIdx >= 0 ? filtered[subjectIdx] : '';
    const bodyLines = subjectIdx >= 0 ? filtered.slice(subjectIdx + 1).filter(l => l.trim() !== '') : [];

    // Subject line: single line, no wrapping — i.e. the subject itself must not
    // contain characters implying it was meant to wrap (we can't detect terminal
    // wrapping after the fact, so this checks the subject is one logical line and
    // not absurdly long, which is the mechanical proxy for "single-line summary").
    if (subject.length > 100) {
        errors.push(`Subject line is ${subject.length} chars — keep commit summaries to a single concise line (soft cap ~72-100 chars).`);
    }

    // Body: if present, each line should look like a short bullet, not a narrative
    // paragraph. Heuristic: flag body lines over ~150 chars (a paragraph-length line)
    // that don't look like a bullet (-, *, or similar leading marker is fine either way,
    // the length is really the tell for "narrative").
    for (const line of bodyLines) {
        if (line.length > 150) {
            errors.push(`Body line looks like a narrative paragraph (${line.length} chars): "${line.slice(0, 60)}...". Keep body lines to short, single-sentence bullets.`);
        }
    }

    // Write back the stripped message (comments preserved, since git needs them
    // for its own diff-below-cutline display; stripping never touches those).
    const newContent = [...filtered, ...(commentLines.length ? [''] : []), ...commentLines].join('\n');
    if (strippedAny) {
        fs.writeFileSync(msgFilePath, newContent, 'utf8');
        console.log('[commit-msg] Stripped attribution/co-author trailer line(s) from commit message.');
    }

    if (subjectIdx === -1) {
        errors.push('Commit message has no subject line.');
    }

    return errors;
}

if (require.main === module) {
    const msgFilePath = process.argv[2];
    if (!msgFilePath) {
        console.error('[commit-msg] No commit message file path given.');
        process.exit(1);
    }
    const errors = run(msgFilePath);
    if (errors.length > 0) {
        console.log('\n[commit-msg] BLOCKED — commit message convention violations:');
        for (const e of errors) console.log(`  - ${e}`);
        process.exit(1);
    }
}

module.exports = { run, isAttributionLine };
